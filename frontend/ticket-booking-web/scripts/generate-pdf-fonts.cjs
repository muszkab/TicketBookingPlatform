const fs = require('fs');
const path = require('path');

const outDir = path.join(__dirname, '..', 'src', 'app', 'features', 'tickets', 'fonts');

const fonts = [
  {
    source: 'node_modules/@expo-google-fonts/roboto/400Regular/Roboto_400Regular.ttf',
    file: 'roboto-regular.base64.ts',
    constant: 'ROBOTO_REGULAR_BASE64'
  },
  {
    source: 'node_modules/@expo-google-fonts/roboto/700Bold/Roboto_700Bold.ttf',
    file: 'roboto-bold.base64.ts',
    constant: 'ROBOTO_BOLD_BASE64'
  }
];

fs.mkdirSync(outDir, { recursive: true });

for (const font of fonts) {
  const base64 = fs.readFileSync(font.source).toString('base64');
  const contents =
    `// Generated by scripts/generate-pdf-fonts.cjs from ${path.basename(font.source)}.\n` +
    `// Roboto is licensed under the Apache License 2.0.\n` +
    `export const ${font.constant} =\n  '${base64}';\n`;
  fs.writeFileSync(path.join(outDir, font.file), contents);
  console.log('wrote', font.file, base64.length, 'chars');
}
